// RunRounds advances the network by a number of rounds
func (simulator *Simulator) RunRounds(numRounds int) {
	for i := 0; i < numRounds; i++ {
		simulator.RunRound()
	}
}

// RunRound advances the network by one round: each shard may produce a block, then the metachain may produce a block.
// Because the metablock is produced last, a destination shard can only execute a cross-shard leg in a block created after
// the metablock that notarizes the source block. Therefore, the two legs are never notarized by the same metablock (as on the real network).
func (simulator *Simulator) RunRound() {
	simulator.round++

	for shard := uint32(0); shard < simulator.numShards; shard++ {
		if simulator.rng.Float64() < simulator.ProbabilityShardBlock {
			simulator.produceShardBlock(shard)
		}
	}

	if simulator.rng.Float64() < simulator.ProbabilityMetaBlock {
		simulator.produceMetaBlock()
	}
}

// Settle runs rounds without generating new transactions, until all pending destination legs are executed and all shard blocks are notarized
func (simulator *Simulator) Settle() {
	simulator.isSettling = true
	defer func() {
		simulator.isSettling = false
	}()

	for i := 0; i < 1000; i++ {
		if len(simulator.pending) == 0 && simulator.isEverythingNotarized() {
			return
		}

		simulator.RunRound()
	}

	panic("mock.Simulator: cannot settle")
}

func (simulator *Simulator) isEverythingNotarized() bool {
	for shard := uint32(0); shard < simulator.numShards; shard++ {
		if simulator.notarizedUpTo[shard] != uint64(simulator.chains[shard].LatestIndex()) {
			return false
		}
	}

	return true
}

func (simulator *Simulator) nextHash(label string) string {
	simulator.txCounter++
	return FakeHash(label, simulator.txCounter)
}

func (simulator *Simulator) produceShardBlock(shard uint32) {
	chain := simulator.chains[shard]
	nonce := uint64(chain.NumBlocks())
	previousBlock, _ := chain.GetBlock(int64(nonce) - 1)

	// Balances are tracked while building the block, so that no account is overdrawn.
	spendable := make(map[string]*big.Int)
	for _, account := range simulator.accountsByShard[shard] {
		balance, _ := chain.GetBalance(account.Address, int64(nonce)-1)
		spendable[account.Address] = balance
	}

	transactions := make([]*types.Transaction, 0)

	// (a) Execute the destination legs that are eligible (their source block is notarized).
	stillPending := make([]*pendingLeg, 0, len(simulator.pending))
	for _, leg := range simulator.pending {
		shouldExecuteNow := leg.destShard == shard && leg.isEligible && simulator.rng.Float64() < 0.8
		if !shouldExecuteNow {
			stillPending = append(stillPending, leg)
			continue
		}

		executed, followUp := simulator.executeDestinationLeg(leg, nonce, spendable)
		transactions = append(transactions, executed...)
		if followUp != nil {
			stillPending = append(stillPending, followUp)
		}
	}
	simulator.pending = stillPending

	// (b) New transactions, sent by accounts of this shard.
	numNewTransactions := simulator.rng.Intn(4)
	if simulator.isSettling {
		numNewTransactions = 0
	}
	for i := 0; i < numNewTransactions; i++ {
		tx := simulator.createTransaction(shard, nonce, spendable)
		if tx != nil {
			transactions = append(transactions, tx)
		}
	}

	// (c) Value coming from outside the served shards (e.g. from the metachain), and rewards.
	if !simulator.isSettling && simulator.rng.Float64() < 0.2 {
		transactions = append(transactions, simulator.createIncomingFromMetachain(shard))
	}
	if !simulator.isSettling && simulator.rng.Float64() < 0.1 {
		transactions = append(transactions, simulator.createReward(shard))
	}

	chain.AddBlock(&types.Block{
		BlockIdentifier:       &types.BlockIdentifier{Index: int64(nonce), Hash: FakeHash("shard-block", shard, nonce)},
		ParentBlockIdentifier: previousBlock.BlockIdentifier,
		Timestamp:             GenesisTimestamp*1000 + int64(simulator.round)*roundDurationMs,
		Transactions:          transactions,
		Metadata: map[string]interface{}{
			"shard":  shard,
			"epoch":  uint32(simulator.round / roundsPerEpoch),
			"round":  simulator.round,
			"status": "on-chain",
		},
	})
}

func (simulator *Simulator) createTransaction(shard uint32, nonce uint64, spendable map[string]*big.Int) *types.Transaction {
	senders := simulator.accountsByShard[shard]
	sender := senders[simulator.rng.Intn(len(senders))]
	receiver := simulator.accounts[simulator.rng.Intn(len(simulator.accounts))]
	if receiver.Address == sender.Address {
		return nil
	}

	// At most a tenth of the balance is sent (some transactions carry no value, e.g. contract calls).
	value := big.NewInt(0)
	if simulator.rng.Float64() < 0.85 {
		maxValue := big.NewInt(0).Div(spendable[sender.Address], big.NewInt(10))
		if maxValue.Sign() > 0 {
			value = big.NewInt(0).Rand(simulator.rng, maxValue)
			value.Add(value, big.NewInt(1))
		}
	}

	cost := big.NewInt(0).Add(value, simulatorFee)
	if spendable[sender.Address].Cmp(cost) < 0 {
		return nil
	}

	spendable[sender.Address] = big.NewInt(0).Sub(spendable[sender.Address], cost)

	hash := simulator.nextHash("tx")
	metadata := newTransactionMetadata(sender.Shard, receiver.Shard, miniblockTypeTransactions, value, sender.Address, receiver.Address, "")
	operations := make([]*types.Operation, 0, 3)

	if value.Sign() > 0 {
		operations = append(operations, newOperation(len(operations), opTypeTransfer, sender.Address, big.NewInt(0).Neg(value), OpStatusSuccess))
	}

	isIntraShard := receiver.Shard == shard
	if isIntraShard {
		if value.Sign() > 0 {
			operations = append(operations, newOperation(len(operations), opTypeTransfer, receiver.Address, value, OpStatusSuccess))
			spendable[receiver.Address] = big.NewInt(0).Add(spendable[receiver.Address], value)
		}
	} else if value.Sign() > 0 {
		// Cross-shard: the receiver is credited later, in its own shard (a shard instance does not report operations of other shards).
		record := &CrossShardTransfer{
			Hash:               hash,
			SourceShard:        shard,
			DestinationShard:   receiver.Shard,
			Sender:             sender.Address,
			Receiver:           receiver.Address,
			Value:              value,
			FailsAtDestination: simulator.rng.Float64() < 0.15,
		}

		simulator.transfers = append(simulator.transfers, record)
		simulator.pending = append(simulator.pending, &pendingLeg{
			kind:        pendingTransfer,
			hash:        hash,
			sourceShard: shard,
			destShard:   receiver.Shard,
			sourceNonce: nonce,
			sender:      sender.Address,
			receiver:    receiver.Address,
			value:       value,
			record:      record,
		})
	}

	// Cross-shard transactions without value have no operations in the destination shard: the shard instance does not report them there.

	operations = append(operations, newOperation(len(operations), opTypeFee, sender.Address, big.NewInt(0).Neg(simulatorFee), OpStatusSuccess))

	return &types.Transaction{
		TransactionIdentifier: &types.TransactionIdentifier{Hash: hash},
		Operations:            operations,
		Metadata:              metadata,
	}
}

// executeDestinationLeg creates the transaction(s) reported by the destination shard for a cross-shard leg.
// It returns a follow-up leg, if any (the refund of a failed transfer travels back to the source shard).
func (simulator *Simulator) executeDestinationLeg(leg *pendingLeg, nonce uint64, spendable map[string]*big.Int) ([]*types.Transaction, *pendingLeg) {
	if leg.kind == pendingRefund {
		// The refund arrives in the shard of the original sender.
		leg.record.RefundExecuted = true
		spendable[leg.receiver] = big.NewInt(0).Add(spendable[leg.receiver], leg.value)

		return []*types.Transaction{
			{
				TransactionIdentifier: &types.TransactionIdentifier{Hash: leg.hash},
				Operations: []*types.Operation{
					newOperation(0, opTypeScResult, leg.receiver, leg.value, OpStatusSuccess),
				},
				Metadata: newTransactionMetadata(leg.sourceShard, leg.destShard, miniblockTypeResults, leg.value, leg.sender, leg.receiver, leg.original),
			},
		}, nil
	}

	leg.record.ExecutedAtDestination = true
	metadata := newTransactionMetadata(leg.sourceShard, leg.destShard, miniblockTypeTransactions, leg.value, leg.sender, leg.receiver, "")

	if !leg.record.FailsAtDestination {
		spendable[leg.receiver] = big.NewInt(0).Add(spendable[leg.receiver], leg.value)

		return []*types.Transaction{
			{
				TransactionIdentifier: &types.TransactionIdentifier{Hash: leg.hash},
				Operations: []*types.Operation{
					newOperation(0, opTypeTransfer, leg.receiver, leg.value, OpStatusSuccess),
				},
				Metadata: metadata,
			},
		}, nil
	}

	// The transfer fails at destination: the receiver is not credited (the operation is reported as failed),
	// and a refund (smart contract result) is sent back to the sender.
	refundHash := simulator.nextHash("refund")
	leg.record.RefundHash = refundHash

	failedTransfer := &types.Transaction{
		TransactionIdentifier: &types.TransactionIdentifier{Hash: leg.hash},
		Operations: []*types.Operation{
			newOperation(0, opTypeTransfer, leg.receiver, leg.value, OpStatusFailure),
		},
		Metadata: metadata,
	}

	// In the shard that generates it, the refund holds the (failed) debit of the receiver, which never had the value.
	refundAtSource := &types.Transaction{
		TransactionIdentifier: &types.TransactionIdentifier{Hash: refundHash},
		Operations: []*types.Operation{
			newOperation(0, opTypeScResult, leg.receiver, big.NewInt(0).Neg(leg.value), OpStatusFailure),
		},
		Metadata: newTransactionMetadata(leg.destShard, leg.sourceShard, miniblockTypeResults, leg.value, leg.receiver, leg.sender, leg.hash),
	}

	followUp := &pendingLeg{
		kind:        pendingRefund,
		hash:        refundHash,
		original:    leg.hash,
		sourceShard: leg.destShard,
		destShard:   leg.sourceShard,
		sourceNonce: nonce,
		sender:      leg.receiver,
		receiver:    leg.sender,
		value:       leg.value,
		record:      leg.record,
	}

	return []*types.Transaction{failedTransfer, refundAtSource}, followUp
}

func (simulator *Simulator) createIncomingFromMetachain(shard uint32) *types.Transaction {
	receivers := simulator.accountsByShard[shard]
	receiver := receivers[simulator.rng.Intn(len(receivers))]
	value := big.NewInt(int64(1 + simulator.rng.Intn(1_000_000)))

	return &types.Transaction{
		TransactionIdentifier: &types.TransactionIdentifier{Hash: simulator.nextHash("from-metachain")},
		Operations: []*types.Operation{
			newOperation(0, opTypeScResult, receiver.Address, value, OpStatusSuccess),
		},
		Metadata: newTransactionMetadata(core.MetachainShardId, shard, miniblockTypeResults, value, "metachain-contract", receiver.Address, ""),
	}
}

func (simulator *Simulator) createReward(shard uint32) *types.Transaction {
	receivers := simulator.accountsByShard[shard]
	receiver := receivers[simulator.rng.Intn(len(receivers))]
	value := big.NewInt(int64(1 + simulator.rng.Intn(1_000_000)))

	// Rewards have no metadata (as returned by the shard instances).
	return &types.Transaction{
		TransactionIdentifier: &types.TransactionIdentifier{Hash: simulator.nextHash("reward")},
		Operations: []*types.Operation{
			newOperation(0, opTypeReward, receiver.Address, value, OpStatusSuccess),
		},
	}
}

func (simulator *Simulator) produceMetaBlock() {
	nonce := uint64(len(simulator.metaBlocks))
	previous := simulator.metaBlocks[nonce-1]
	notarized := make([]metachain.NotarizedBlock, 0)

	for shard := uint32(0); shard < simulator.numShards; shard++ {
		latest := uint64(simulator.chains[shard].LatestIndex())
		numPending := latest - simulator.notarizedUpTo[shard]
		if numPending == 0 {
			continue
		}

		// Most of the time, all pending blocks are notarized. Sometimes none, sometimes only a part of them.
		numToNotarize := numPending
		dice := simulator.rng.Float64()
		if dice < 0.15 {
			numToNotarize = 0
		} else if dice < 0.3 {
			numToNotarize = 1 + uint64(simulator.rng.Int63n(int64(numPending)))
		}

		for i := uint64(1); i <= numToNotarize; i++ {
			shardNonce := simulator.notarizedUpTo[shard] + i
			block, _ := simulator.chains[shard].GetBlock(int64(shardNonce))
			notarized = append(notarized, metachain.NotarizedBlock{Shard: shard, Nonce: shardNonce, Hash: block.BlockIdentifier.Hash})
		}

		simulator.notarizedUpTo[shard] += numToNotarize
	}

	// The order of the notarized blocks, within a metablock, is not guaranteed.
	simulator.rng.Shuffle(len(notarized), func(i, j int) { notarized[i], notarized[j] = notarized[j], notarized[i] })

	block := &metachain.Block{
		Nonce:       nonce,
		Hash:        FakeHash("meta-block", nonce),
		PrevHash:    previous.Hash,
		TimestampMs: GenesisTimestamp*1000 + int64(simulator.round)*roundDurationMs,
		Epoch:       uint32(simulator.round / roundsPerEpoch),
		Round:       simulator.round,
		Notarized:   notarized,
	}

	simulator.metaBlocks = append(simulator.metaBlocks, block)
	simulator.metaSource.AddBlock(block)
	simulator.metaSource.SetHighestFinalNonce(nonce)

	// Legs whose source block is now notarized can be executed by the destination shard, from now on.
	for _, leg := range simulator.pending {
		if leg.sourceNonce <= simulator.notarizedUpTo[leg.sourceShard] {
			leg.isEligible = true
		}
	}
}

func newOperation(index int, operationType string, address string, value *big.Int, status string) *types.Operation {
	return &types.Operation{
		OperationIdentifier: &types.OperationIdentifier{Index: int64(index)},
		Type:                operationType,
		Status:              &status,
		Account:             &types.AccountIdentifier{Address: address},
		Amount:              &types.Amount{Value: value.String(), Currency: NativeCurrency},
	}
}

// newTransactionMetadata creates the transaction metadata, with the keys set by the shard instances
func newTransactionMetadata(sourceShard uint32, destinationShard uint32, miniblockType string, value *big.Int, sender string, receiver string, originalTransaction string) map[string]interface{} {
	metadata := map[string]interface{}{
		"sourceShard":      sourceShard,
		"destinationShard": destinationShard,
		"miniblockType":    miniblockType,
		"value":            value.String(),
		"sender":           sender,
		"receiver":         receiver,
	}

	if len(originalTransaction) > 0 {
		metadata["originalTransaction"] = originalTransaction
	}

	return metadata
}
