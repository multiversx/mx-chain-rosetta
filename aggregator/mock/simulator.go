// Backends returns the fake shard instances, as a set
func (simulator *Simulator) Backends() *backend.Set {
	byShard := make(map[uint32]backend.ShardBackend, len(simulator.backends))
	for shard, shardBackend := range simulator.backends {
		byShard[uint32(shard)] = shardBackend
	}

	set, err := backend.NewSet(byShard)
	if err != nil {
		panic(err)
	}

	return set
}

